using System;

namespace Mvk.Engine.World.Block
{
    /// <summary>
    /// Перечень дейстыий в момент изменения блока
    /// Используем с префиксом "c".
    /// Префикс "n" используется в методах Block.OnBreakBlock
    /// </summary>
    [Flags]
    public enum BlockFlag
    {
        None = 0,
        /// <summary>
        /// Пометка частички старого блока
        /// Цель: запустить на сервере частички при разрушении блока.
        /// Только сервер.
        /// </summary>
        Particle = 1,
        /// <summary>
        /// Пометка уведомить соседей
        /// Цель: если блок зависимы, демонтировался или применил иное действие. 
        /// Пример: трава, блок земли убрать, трава диспавнится. дверь, блок опорной петли убрать дверь диспавнится.
        /// Только сервер.
        /// </summary>
        Notify = 2,
        /// <summary>
        /// Звуковое сопровождение сломанного блока
        /// Только сервер.
        /// </summary>
        Sound = 4,
        /// <summary>
        /// Проверка доп жидкости
        /// Цель: если флага нет, то жидкость типа уберёт но надо чтоб был только воздух. !!! Проверить.
        /// </summary>
        Liquid = 8,
        /// <summary>
        /// OnBreakBlock отключить
        /// Только сервер.
        /// </summary>
        Break = 16,

        /// <summary>
        /// Комплект Тихо, незаметная смена блока 44
        /// </summary>
        cQuiet = Liquid,

        /// <summary>
        /// Комплект Соседи, незаметная, но с проверкой соседних блоков 46
        /// </summary>
        cNotify = Notify | Liquid,

        /// <summary>
        /// Комплект Частички, визуально запускаем частички 47
        /// </summary>
        cParticle = Particle | Notify | Liquid,

        /// <summary>
        /// Комплект Звук, звуковой эффект поломки блока и частички 63
        /// </summary>
        cSound = Particle | Notify | Sound | Liquid,

        /// <summary>
        /// Комплект Без проверки удаления тихо 108. 
        /// Только для удаления дополнительных блоков! Нужен отдельный список для Notify
        /// </summary>
        nBreakQuiet = Liquid | Break,
        /// <summary>
        /// Комплект Без проверки удаления с частичками 109. 
        /// Только для удаления дополнительных блоков! Нужен отдельный список для Notify
        /// </summary>
        nBreakParticle = Particle | Liquid | Break

    }
}

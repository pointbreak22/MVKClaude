#nullable enable
namespace Mvk.Engine.World.Gen
{
    /// <summary>
    /// Режим генерации мира, хранится в сохранении игры (GameSettings, тег GenMode): мир не меняет режим
    /// </summary>
    public enum EnumGenerationMode : byte
    {
        /// <summary>
        /// Как в оригинале: рельеф последовательно, трава из общего генератора случайных чисел
        /// (мир зависит от порядка генерации чанков), совпадает с эталоном island.csv
        /// </summary>
        Original = 0,
        /// <summary>
        /// [ПОВЕДЕНИЕ] Рельеф пакета чанков считается пулом потоков, случайные числа рельефа (трава) засеваются
        /// от зерна и координат чанка: мир не зависит от порядка генерации, но отличается от оригинала (эталон
        /// island-parallel.csv)
        /// </summary>
        Parallel = 1
    }
}
